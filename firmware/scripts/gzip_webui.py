#
# Web UI packaging, run before every build:
#  - Always: gzip data/ into a generated C header (WebUiAssets.h) that is compiled into the
#    firmware, so a plain `pio run -t upload` (or one merged image) ships the UI. Nothing
#    else needs flashing.
#  - buildfs/uploadfs: also stage gzipped copies for the optional LittleFS image, as before.
import gzip
import os
import re
import shutil

Import("env")

MIME = {
    ".html": "text/html",
    ".js": "application/javascript",
    ".css": "text/css",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
}

src = os.path.join(env.subst("$PROJECT_DIR"), "data")


def gz(data):
    # mtime=0 keeps the output (and its ETag) identical for identical sources
    return gzip.compress(data, compresslevel=9, mtime=0)


def data_files():
    for root, _, files in os.walk(src):
        for name in sorted(files):
            path = os.path.join(root, name)
            rel = os.path.relpath(path, src).replace(os.sep, "/")
            yield rel, path


# --- Embedded copy (every build) ---
inc_dir = os.path.join(env.subst("$BUILD_DIR"), "webui_embedded")
os.makedirs(inc_dir, exist_ok=True)
lines = [
    "// Generated by scripts/gzip_webui.py from data/ - do not edit",
    "#pragma once",
    "#include <cstddef>",
    "#include <cstdint>",
    "",
    "struct WebUiAsset {",
    "    const char*    path;  // URL path, e.g. \"/app.js\"",
    "    const char*    mime;",
    "    const uint8_t* gz;    // gzip-compressed body",
    "    size_t         len;",
    "    uint32_t       etag;  // content hash, for If-None-Match",
    "};",
    "",
]
entries = []
total = 0
for i, (rel, path) in enumerate(data_files()):
    with open(path, "rb") as f:
        body = gz(f.read())
    total += len(body)
    sym = "kWebUi%d_%s" % (i, re.sub(r"\W", "_", rel))
    mime = MIME.get(os.path.splitext(rel)[1].lower(), "application/octet-stream")
    etag = 2166136261  # FNV-1a
    for b in body:
        etag = ((etag ^ b) * 16777619) & 0xFFFFFFFF
    hexbytes = ",".join("0x%02x" % b for b in body)
    lines.append("static const uint8_t %s[] = {%s};" % (sym, hexbytes))
    entries.append('    {"/%s", "%s", %s, sizeof(%s), 0x%08xu},' % (rel, mime, sym, sym, etag))
lines.append("")
lines.append("static const WebUiAsset kWebUiAssets[] = {")
lines.extend(entries)
lines.append("};")
lines.append("static constexpr size_t kWebUiAssetCount = sizeof(kWebUiAssets) / sizeof(kWebUiAssets[0]);")

header = os.path.join(inc_dir, "WebUiAssets.h")
content = "\n".join(lines) + "\n"
old = open(header).read() if os.path.exists(header) else None
if content != old:  # untouched header = no needless recompile
    with open(header, "w") as f:
        f.write(content)
env.Append(CPPPATH=[inc_dir])
print("Web UI: embedded %d files, %d bytes gzipped" % (len(entries), total))

# --- LittleFS image (buildfs/uploadfs only) ---
FS_TARGETS = {"buildfs", "uploadfs", "uploadfsota"}

if FS_TARGETS & set(COMMAND_LINE_TARGETS):
    out = os.path.join(env.subst("$BUILD_DIR"), "webui")
    shutil.rmtree(out, ignore_errors=True)
    for rel, path in data_files():
        dst = os.path.join(out, rel + ".gz")
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(path, "rb") as f:
            data = f.read()
        with open(dst, "wb") as f:
            f.write(gz(data))
    print("Web UI: gzipped %s -> %s" % (src, out))
    env.Replace(PROJECT_DATA_DIR=out)
